def translate(language, english, **values):
    message = ARABIC[english] if language == "ar" else english
    return message.format(**values) if values else message


def arabic_days(days):
    if days < 3:
        return ("0 يوم", "يوم واحد", "يومان")[days]
    suffix = "أيام" if 3 <= days % 100 <= 10 else "يومًا"
    return f"{days} {suffix}"
